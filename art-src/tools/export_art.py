"""Export generated art (art-src/cast, art-src/places) to optimized WebP in public/art and
write src/art/assets.ts with the ids that have images. Run after adding or replacing art."""
from pathlib import Path
from PIL import Image
ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'public/art'
cast, places = [], []
faces = {}
for f in sorted((ROOT / 'art-src/cast').glob('*.png')):
    im = Image.open(f).convert('RGBA')
    a = im.split()[3]
    x0, y0, x1, y1 = a.getbbox()
    full = im.resize((640, round(640 * im.height / im.width)), Image.LANCZOS)
    full.save(OUT / 'cast' / f'{f.stem}.webp', 'WEBP', quality=80, method=6)
    # face: centre of the opaque span in the band just below the top of the head
    W, H = im.size
    band = [y0 + int(H * k) for k in (0.06, 0.1, 0.14, 0.18)]
    cxs = []
    for y in band:
        row = [a.getpixel((x, y)) for x in range(0, W, 4)]
        xs = [i * 4 for i, v in enumerate(row) if v > 128]
        if xs: cxs.append((xs[0] + xs[-1]) / 2)
    cx = sum(cxs) / len(cxs) if cxs else W / 2
    side = int(W * 0.46)
    top = max(0, y0 - int(H * 0.01))
    left = int(min(max(0, cx - side / 2), W - side))
    face = im.crop((left, top, left + side, top + side)).resize((256, 256), Image.LANCZOS)
    face.save(OUT / 'cast' / f'{f.stem}-face.webp', 'WEBP', quality=82, method=6)
    cast.append(f.stem)
for f in sorted((ROOT / 'art-src/places').glob('*.png')):
    im = Image.open(f).convert('RGB')
    W, H = im.size
    h = round(W * 9 / 16)
    top = max(0, round((H - h) * 0.45))
    im = im.crop((0, top, W, top + h)).resize((1600, 900), Image.LANCZOS)
    im.save(OUT / 'places' / f'{f.stem}.webp', 'WEBP', quality=76, method=6)
    places.append(f.stem)
(ROOT / 'src/art/assets.ts').write_text(
    '// Generated by art-src/tools/export_art.py — ids with illustrated art in public/art.\n'
    f'export const CAST_ART = new Set<string>({cast!r});\n'.replace("'", '"').replace('[', '[').replace(']', ']')
    + f'export const PLACE_ART = new Set<string>({places!r});\n'.replace("'", '"')
)
print('cast', len(cast), 'places', len(places))
